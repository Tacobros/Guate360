const I18nEngine = {

  currentLang: 'es',
  supportedLangs: ['es', 'en', 'fr'],

  init() {
    const saved = localStorage.getItem('g360_lang');
    const browserLang = navigator.language.slice(0, 2);
    this.currentLang = saved
      || (this.supportedLangs.includes(browserLang) ? browserLang : 'es');
    this.apply();
    this.renderSwitcher();
  },

  t(key) {
    return (I18N[this.currentLang] && I18N[this.currentLang][key])
      || (I18N['es'] && I18N['es'][key])
      || key;
  },

  apply() {
    document.documentElement.lang = this.currentLang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (key) el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = this.t(el.dataset.i18nHtml);
    });
    // Update active lang button
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === this.currentLang);
    });
  },

  setLang(lang) {
    if (!this.supportedLangs.includes(lang)) return;
    this.currentLang = lang;
    localStorage.setItem('g360_lang', lang);
    this.apply();
    // Re-render dynamic content if needed
    if (typeof initFilters === 'function') {
      const evt = new Event('langchange');
      document.dispatchEvent(evt);
    }
  },

  renderSwitcher() {
    const containers = document.querySelectorAll('.lang-switcher');
    const flags = { es: '🇬🇹 ES', en: '🇺🇸 EN', fr: '🇫🇷 FR' };
    containers.forEach(container => {
      container.innerHTML = this.supportedLangs.map(lang =>
        `<button class="lang-btn ${lang === this.currentLang ? 'active' : ''}"
          data-lang="${lang}"
          onclick="I18nEngine.setLang('${lang}')"
          aria-label="Switch to ${lang.toUpperCase()}">${flags[lang]}</button>`
      ).join('');
    });
  }
};

/* Auto-init when DOM is ready */
document.addEventListener('DOMContentLoaded', () => I18nEngine.init());
